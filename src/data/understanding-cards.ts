export const findUnderstandingCard = (query?: string | null): UnderstandingCard | null => {
  if (!query) return null;
  const clean = query.trim().toLowerCase();
  
  // Direct match
  if (UNDERSTANDING_CARDS_MAP[query]) {
    return UNDERSTANDING_CARDS_MAP[query];
  }
  if (UNDERSTANDING_CARDS_MAP[clean]) {
    return UNDERSTANDING_CARDS_MAP[clean];
  }
  
  // Normalized match
  const normalized = clean.replace(/[-_]/g, '');
  for (const card of UNDERSTANDING_CARDS) {
    if (card.id.toLowerCase().replace(/[-_]/g, '') === normalized) return card;
    if (card.sourceId.toLowerCase().replace(/[-_]/g, '') === normalized) return card;
    if (clean.includes(card.author.toLowerCase()) || card.title.toLowerCase().includes(clean)) return card;
  }
  
  return null;
};
