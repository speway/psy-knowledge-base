export const CONTEXTUAL_GUIDES_MAP = CONTEXTUAL_GUIDES.reduce<Record<string, ContextualGuide>>((acc, guide) => {
  acc[guide.id] = guide;
  acc[guide.topicTag] = guide;
  return acc;
}, {});

export const findContextualGuide = (query?: string | null): ContextualGuide | null => {
  if (!query) return null;
  const clean = query.trim().toLowerCase();
  
  if (CONTEXTUAL_GUIDES_MAP[clean]) {
    return CONTEXTUAL_GUIDES_MAP[clean];
  }
  
  for (const guide of CONTEXTUAL_GUIDES) {
    if (guide.id.toLowerCase().includes(clean) || clean.includes(guide.topicTag.toLowerCase())) {
      return guide;
    }
    if (guide.title.toLowerCase().includes(clean)) {
      return guide;
    }
  }
  return null;
};
